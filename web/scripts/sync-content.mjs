#!/usr/bin/env node
// Copies shared/content JSON into web/src/data/content and generates an index.ts
// that statically imports every file (works with Next.js static export).
// Runs automatically on `npm run dev` / `npm run build`.
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const src = join(root, '..', 'shared', 'content');
const dest = join(root, 'src', 'data', 'content');

function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (name.endsWith('.json')) acc.push(p);
  }
  return acc;
}

function safeIdent(p) {
  return 'f_' + p.replace(/[^a-zA-Z0-9]+/g, '_').replace(/^_|_$/g, '');
}

if (!existsSync(src)) {
  console.warn('[sync-content] shared/content not found — using previously synced data if any.');
  if (!existsSync(dest)) mkdirSync(dest, { recursive: true });
  process.exit(0);
}

rmSync(dest, { recursive: true, force: true });
mkdirSync(dest, { recursive: true });
cpSync(src, dest, { recursive: true });

const files = walk(dest).sort();
const imports = [];
const entries = [];
for (const abs of files) {
  const rel = './' + relative(dest, abs).split(sep).join('/');
  const id = safeIdent(rel);
  imports.push(`import ${id} from '${rel}';`);
  entries.push(`  { path: ${JSON.stringify(rel)}, data: ${id} },`);
}

const index = `// AUTO-GENERATED by scripts/sync-content.mjs — do not edit.
${imports.join('\n')}

export interface ContentFile { path: string; data: unknown }

export const contentFiles: ContentFile[] = [
${entries.join('\n')}
];
`;
writeFileSync(join(dest, 'index.ts'), index, 'utf8');
console.log(`[sync-content] synced ${files.length} JSON files -> ${dest} (+ index.ts)`);

// pdf.js worker for the PDF reader (served from public/ so it works offline).
const workerSrc = join(root, 'node_modules', 'pdfjs-dist', 'build', 'pdf.worker.min.mjs');
const workerDest = join(root, 'public', 'pdf.worker.mjs');
if (existsSync(workerSrc)) {
  mkdirSync(join(root, 'public'), { recursive: true });
  cpSync(workerSrc, workerDest);
  console.log('[sync-content] copied pdf.js worker -> public/pdf.worker.mjs');
} else {
  console.warn('[sync-content] pdfjs-dist not installed yet; PDF worker copy skipped.');
}
